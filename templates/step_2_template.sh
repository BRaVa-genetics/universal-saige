# Note that because of how the containers are set up, the files passed must be
# contained within the working directory. To change this, edit the
# `run_container.sh` script which calls the docker/singularity container for
# all steps.
#
# GENOTYPES: PLINK 2 (.pgen/.pvar/.psam) is RECOMMENDED -- it is what the
# All of Us runs used, it is smaller, and the SAIGE image reads it directly.
# PLINK 1 (.bed/.bim/.fam) also works. A VCF is REFUSED: convert it once,
#     resources/plink2 --vcf exome.chr20.vcf.gz --make-pgen --out exome.chr20
# rather than paying for a conversion on every chromosome of every phenotype.

# Which chromosome to analyse. Spell it as the .pvar/.bim does: if the first
# column reads '20', pass 20, not chr20 (a mismatch is refused, showing the
# file's spelling).
chrom=["chr20"]

# Plink 2 filename prefix of .pgen/.pvar/.psam for WES (or WGS restricted to
# exons). Relative to, and contained in, the current working directory.
pgen=["path/to/pgen/files"]
# ... or the Plink 1 prefix of .bed/.bim/.fam, if that is what you have.
plink=["path/to/plink/files"]

# Model file and variance-ratio file from SAIGE step 1: ${out_step1}.rda and
# ${out_step1}.varianceRatio.txt, relative to the current working directory.
model_file=["path/to/model/file"]
variance_ratio=["path/to/varianceratio"]

# The BRaVa group files: the October 2026 rebuild, one set per biobank, in your
# biobank's bucket (see its README.md). Each chromosome has four files (three on
# chrY: no scallion scores there); use the ones in biobank_ids/ if your genotype
# files use the variant IDs shown there, otherwise the ones in chr_pos_ref_alt/:
#   <biobank>.chrN.new_rules.saige_group.txt.gz    run 1: SAIGE-GENE+, seven masks
#   <biobank>.chrN.am_moderate.saige_group.txt.gz  run 2: SAIGE-GENE+, AlphaMissense >= 0.906
#   <biobank>.chrN.flexrv_AMPCT.txt.gz             run 3: FlexRV, AlphaMissense percentile, ready to use
#   <biobank>.chrN.flexrv_SCALLION.txt.gz          run 4: FlexRV, scallion percentile, ready to use
# (an earlier <biobank>.chrN.flexrv_AM.txt.gz, raw AlphaMissense, is superseded by flexrv_AMPCT)
group_file=["path/to/<biobank>.chrN.new_rules.saige_group.txt.gz"]
# The masks for run 1: ':' joins labels into ONE mask, ',' separates
# masks. The labels of the October 2026 files are pLoF, damaging_missense,
# spliceai2_gt040, other_missense, synonymous and non_coding; spell them exactly
# (step 2 refuses a label the file does not have, and lists the ones it has).
annots="pLoF,damaging_missense,pLoF:damaging_missense,pLoF:damaging_missense:spliceai2_gt040,synonymous,other_missense,pLoF:damaging_missense:spliceai2_gt040:other_missense:synonymous"
# (Older BRaVa group files use the labels damaging_missense_or_protein_altering and
# other_missense_or_protein_altering, and have no spliceai2_gt040: with one of those,
# annots="pLoF,damaging_missense_or_protein_altering,other_missense_or_protein_altering,synonymous,pLoF:damaging_missense_or_protein_altering,pLoF:damaging_missense_or_protein_altering:other_missense_or_protein_altering:synonymous")

# Output prefix for the data generated by this step (step 2).
out_step2=["out"]

# is singularity (or apptainer) available? If not, it is assumed that docker is available.
IS_SINGULARITY={"false","true"}

# The GRM from step 0 and its sample IDs:
# ${out_step0}_relatednessCutoff_${relatedness_cutoff}_5000_randomMarkersUsed.sparseGRM.mtx
# and the same with .sampleIDs.txt appended.
GRM=["path/to/GRM/file"]
GRM_samples=["path/to/GRM/sampleID/file"]

# The relatedness cutoff steps 0 and 1 used (MUST be the same; nothing in SAIGE
# checks it).
relatedness_cutoff=0.05

# FOUR RUNS per chromosome and phenotype, all on the October 2026 BRaVa files:
#   run 1  SAIGE-GENE+ (SKAT-O), seven masks, with the SpliceAI2 >= 0.40 category
#   run 2  SAIGE-GENE+ (SKAT-O), the AlphaMissense >= 0.906 mask
#   run 3  FlexRV, AlphaMissense within-gene percentile weights
#   run 4  FlexRV, scallion within-gene percentile weights (chromosomes 1-22 and X)
# Results: <prefix>.txt, one row per gene, mask and max MAF. Columns include log10
# p-values (log10_Pvalue, ... : exact even where Pvalue reads 0) and nEff_Burden (the
# effective number of carriers behind each burden test), right after SE_Burden. Add
# '--log10P FALSE --nEff FALSE' to a call only if your downstream code reads columns
# by position rather than by name.

# ---- run 1. SAIGE-GENE+ (SKAT-O): seven masks x three max MAFs ---------------
# Also writes the per-variant results of every variant in the masks,
# ${out_step2}.skato.txt.singleAssoc.txt.
bash 02_step2_SPAtests_variant_and_gene.sh \
    --chr $chrom \
    --testType group \
    --pgen ${pgen} \
    --modelFile ${model_file} \
    --varianceRatio ${variance_ratio} \
    --groupFile ${group_file} \
    --annotations ${annots} \
    --outputPrefix ${out_step2}.skato \
    --isSingularity $IS_SINGULARITY \
    --sparseGRM ${GRM} \
    --sparseGRMID ${GRM_samples} \
    --relatednessCutoff ${relatedness_cutoff}

# ---- run 2. SAIGE-GENE+ (SKAT-O): AlphaMissense >= 0.906 (ACMG PP3 Moderate) --
# Its own group file, one label (am_moderate): missense variants whose AlphaMissense
# score reaches 0.906. No per-variant file (--singleInGroup FALSE): its variants are
# in run 1's already.
am_group_file=["path/to/<biobank>.chrN.am_moderate.saige_group.txt.gz"]
bash 02_step2_SPAtests_variant_and_gene.sh \
    --chr $chrom \
    --testType group \
    --pgen ${pgen} \
    --modelFile ${model_file} \
    --varianceRatio ${variance_ratio} \
    --groupFile ${am_group_file} \
    --annotations am_moderate \
    --singleInGroup FALSE \
    --outputPrefix ${out_step2}.am_moderate \
    --isSingularity $IS_SINGULARITY \
    --sparseGRM ${GRM} \
    --sparseGRMID ${GRM_samples} \
    --relatednessCutoff ${relatedness_cutoff}

# ---- run 3. FlexRV with AlphaMissense percentile weights (one mask, burden statistic)
# The release's FlexRV file is ready to use (its score:AMPCT line is built in): LoF 1.0,
# a missense variant its percentile among all possible missense variants of its gene
# (FlexRV paper; README, step 4). ONE mask, which must include the SpliceAI label: that
# category holds missense variants with a splice call, which carry scores (step 2
# refuses a mask that leaves scored variants out). The pooled FlexRV p per gene is the
# row with Group == Cauchy; a hit whose nEff_Burden is small (below ~10) rests on a few
# people. FlexRV writes no per-variant file by default (their variants are in run 1's).
flexrv_group_file_AMPCT=["path/to/<biobank>.chrN.flexrv_AMPCT.txt.gz"]
flexrv_mask="pLoF:damaging_missense:other_missense:spliceai2_gt040"
bash 02_step2_SPAtests_variant_and_gene.sh \
    --chr $chrom \
    --pgen ${pgen} \
    --modelFile ${model_file} \
    --varianceRatio ${variance_ratio} \
    --groupFile ${flexrv_group_file_AMPCT} \
    --flexRVscore AMPCT \
    --annotations ${flexrv_mask} \
    --outputPrefix ${out_step2}.flexrv_AMPCT \
    --isSingularity $IS_SINGULARITY \
    --sparseGRM ${GRM} \
    --sparseGRMID ${GRM_samples} \
    --relatednessCutoff ${relatedness_cutoff}

# ---- run 4. FlexRV with scallion percentile weights (chromosomes 1-22 and X) ----
# The same variants and mask as run 3, scored by scallion's within-gene percentile
# (score:SCALLION). One score line per file, so a second file and a second run.
# There is no scallion file for chrY: skip this run there.
flexrv_group_file_SCALLION=["path/to/<biobank>.chrN.flexrv_SCALLION.txt.gz"]
bash 02_step2_SPAtests_variant_and_gene.sh \
    --chr $chrom \
    --pgen ${pgen} \
    --modelFile ${model_file} \
    --varianceRatio ${variance_ratio} \
    --groupFile ${flexrv_group_file_SCALLION} \
    --flexRVscore SCALLION \
    --annotations ${flexrv_mask} \
    --outputPrefix ${out_step2}.flexrv_SCALLION \
    --isSingularity $IS_SINGULARITY \
    --sparseGRM ${GRM} \
    --sparseGRMID ${GRM_samples} \
    --relatednessCutoff ${relatedness_cutoff}

